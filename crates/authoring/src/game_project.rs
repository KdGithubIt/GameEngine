    #[test]
    fn scene_and_prefab_roundtrips_preserve_sidecar_component_id() {
        let (_directory, project) = project();
        let component_path = create_rust_script(
            &project,
            RustScriptKind::Component,
            "Health",
            RustScriptSchedule::Update,
        )
        .unwrap();
        let component_id = load_component_metadata(&component_metadata_path(&component_path))
            .unwrap()
            .component_id;
        let component_type = crate::ComponentTypeId::new(component_id.clone());
        let entity_id = crate::EntityId::generate();
        let mut scene = crate::AuthoringScene::new();
        let mut transaction = crate::Transaction::begin(&scene);
        transaction.apply(crate::AuthoringCommand::CreateEntity {
            id: entity_id.clone(),
            name: "player".to_owned(),
            parent: None,
        });
        transaction.apply(crate::AuthoringCommand::AddComponent {
            entity: entity_id.clone(),
            component_type: component_type.clone(),
            value: crate::Value::Object(Default::default()),
        });
        transaction.commit(&mut scene).unwrap();

        // The stable ID must survive a free-form relocation as well.
        move_rust_script(
            &project,
            Path::new("components/health.rs"),
            Path::new("player/health.rs"),
        )
        .unwrap();

        let scene_json = scene.to_canonical_json().unwrap();
        let reopened_scene = crate::load_scene_from_json(&scene_json).unwrap();
        assert!(reopened_scene
            .entity(&entity_id)
            .unwrap()
            .components
            .contains_key(&component_type));

        let prefab = crate::PrefabAsset::from_selection(reopened_scene.entities()).unwrap();
        let prefab_json = prefab.to_json().unwrap();
        let reopened_prefab = crate::PrefabAsset::from_json(&prefab_json).unwrap();
        assert!(reopened_prefab
            .entities
            .values()
            .any(|entity| entity.components.contains_key(&component_type)));
        assert!(scene_json.contains(&component_id));
        assert!(prefab_json.contains(&component_id));
        assert_eq!(
            load_component_metadata(&component_metadata_path(
                &project.rust_scripts_dir().join("player/health.rs")
            ))
            .unwrap()
            .component_id,
            component_id
        );
    }

